/**
 * Builds the current validated ConferenceProgram as an immutable app asset.
 * Provider-specific mapping lives in scripts/providers/; this file only owns
 * serialization, content hashing, and generated build metadata.
 *
 * Run from app/: `pnpm run program` (plain Node, type-stripped).
 */
import { createHash } from "node:crypto";
import {
  mkdirSync,
  readdirSync,
  readFileSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";

import type { ConferenceProgram } from "../src/shared/program.ts";
import { conferenceProgramJsonSchema } from "../src/shared/program.ts";
import {
  adaptAaicProgram,
  type RawEventPilotItem,
  type RawEventPilotPerson,
} from "./providers/eventpilot-aaic.ts";

const APP_ROOT = join(import.meta.dirname, "..");
const REPOSITORY_ROOT = join(APP_ROOT, "..");
const DATA_DIR = join(REPOSITORY_ROOT, "data", "aaic_2026");

export function programContentHash(program: ConferenceProgram): string {
  return createHash("sha256")
    .update(JSON.stringify(program))
    .digest("hex")
    .slice(0, 8);
}

function main(): void {
  const rawSessions: RawEventPilotItem[] = JSON.parse(
    readFileSync(join(DATA_DIR, "sessions.json"), "utf8"),
  );
  const rawPeople: Record<string, RawEventPilotPerson> = JSON.parse(
    readFileSync(join(DATA_DIR, "people.json"), "utf8"),
  );

  const program = adaptAaicProgram(rawSessions, rawPeople);
  const contentHash = programContentHash(program);
  const assetName = `program.${contentHash}.json`;

  const publicDir = join(APP_ROOT, "public");
  mkdirSync(publicDir, { recursive: true });
  for (const stale of readdirSync(publicDir).filter(
    (file) =>
      file.startsWith("program.") &&
      file.endsWith(".json") &&
      file !== assetName,
  )) {
    unlinkSync(join(publicDir, stale));
  }
  writeFileSync(join(publicDir, assetName), JSON.stringify(program));

  // Content-hashed names never change content: cache forever.
  writeFileSync(
    join(publicDir, "_headers"),
    [
      `/${assetName}`,
      "  Cache-Control: public, max-age=31536000, immutable",
      "/assets/*",
      "  Cache-Control: public, max-age=31536000, immutable",
      "",
    ].join("\n"),
  );

  const generatedDir = join(APP_ROOT, "src", "shared", "generated");
  mkdirSync(generatedDir, { recursive: true });
  writeFileSync(
    join(generatedDir, "program-meta.ts"),
    [
      "// Generated by scripts/build-program.ts — do not edit.",
      `export const PROGRAM_CONFERENCE = ${JSON.stringify(program.conference)} as const;`,
      `export const PROGRAM_HASH = '${contentHash}';`,
      `export const PROGRAM_PATH = '/${assetName}';`,
      "",
    ].join("\n"),
  );

  const schemaDir = join(REPOSITORY_ROOT, "schema");
  mkdirSync(schemaDir, { recursive: true });
  writeFileSync(
    join(schemaDir, "conference-program-v1.schema.json"),
    `${JSON.stringify(conferenceProgramJsonSchema(), null, 2)}\n`,
  );

  const presentations = program.sessions.reduce(
    (count, session) => count + session.presentations.length,
    0,
  );
  console.log(
    `wrote ${assetName}: ${program.days.length} days, ${program.sessions.length} sessions, ` +
      `${presentations} presentations, ${Object.keys(program.people).length} people`,
  );
}

if (process.argv[1] === import.meta.filename) main();
